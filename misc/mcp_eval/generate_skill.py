"""Regenerate the tool reference in skills/parcs-cluster/SKILL.md from the live MCP server.

The block between the BEGIN/END GENERATED TOOL REFERENCE markers is rebuilt from the server's
tools/list (names, descriptions, argument schemas), so the skill cannot drift from the contract
the server actually implements. Everything outside the markers — the hand-written guide and the
lessons the agent adds during reflection — is kept as it is.

    uv run python generate_skill.py                 # server from MCP__CLUSTER_URL in .env
    uv run python generate_skill.py --url http://127.0.0.1:18080 --check   # fail if out of date
"""

import asyncio
import sys
from argparse import ArgumentParser
from pathlib import Path

from mcp import ClientSession
from mcp.client.streamable_http import streamablehttp_client

SKILL_FILE = Path(__file__).resolve().parent / "skills" / "parcs-cluster" / "SKILL.md"
BEGIN = "<!-- BEGIN GENERATED TOOL REFERENCE -->"
END = "<!-- END GENERATED TOOL REFERENCE -->"

# Reading order of the reference; tools the server adds later are appended by name.
ORDER = ["get_cluster_info", "create_session", "run_layer", "submit_layer", "wait_layer",
         "get_layer_result", "list_layers", "list_sessions", "cancel_layer"]


def _type_of(schema: dict) -> str:
    if "anyOf" in schema:
        return " | ".join(_type_of(s) for s in schema["anyOf"])
    kind = schema.get("type")
    if isinstance(kind, list):
        return " | ".join(kind)
    if kind == "array":
        return f"{_type_of(schema.get('items', {}))}[]"
    if kind == "object" and "additionalProperties" in schema:
        return f"{{[key]: {_type_of(schema['additionalProperties'])}}}"
    return kind or "any"


def render(tools: list) -> str:
    lines = [
        BEGIN,
        "<!-- Generated by generate_skill.py from the server's tools/list. Do not edit by hand. -->",
        "",
        "## MCP Tools",
        "",
    ]
    rank = {name: i for i, name in enumerate(ORDER)}
    for tool in sorted(tools, key=lambda t: (rank.get(t.name, len(ORDER)), t.name)):
        schema = tool.inputSchema or {}
        props = schema.get("properties", {})
        required = set(schema.get("required", []))
        signature = ", ".join(f"{n}{'' if n in required else '?'}" for n in props)
        lines += [f"### `{tool.name}({signature})`", "", (tool.description or "").strip(), ""]
        if props:
            lines += ["| Argument | Type | Required | Description |", "|---|---|---|---|"]
            for name, prop in props.items():
                desc = (prop.get("description") or "").replace("|", "\\|").replace("\n", " ")
                default = f" Default: `{prop['default']}`." if "default" in prop and prop["default"] is not None else ""
                lines.append(f"| `{name}` | `{_type_of(prop).replace('|', chr(92) + '|')}` | {'yes' if name in required else 'no'} | {desc}{default} |")
            lines.append("")
    lines.append(END)
    return "\n".join(lines)


async def fetch_tools(url: str) -> list:
    async with streamablehttp_client(url) as (read, write, _):
        async with ClientSession(read, write) as session:
            await session.initialize()
            return (await session.list_tools()).tools


def main() -> int:
    parser = ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--url", help="MCP server base URL (default: MCP__CLUSTER_URL)")
    parser.add_argument("--check", action="store_true", help="Exit 1 if SKILL.md is out of date; write nothing")
    args = parser.parse_args()

    url = args.url
    if not url:
        from mcp_eval.config import config
        url = config.mcp.cluster_url
    url = url.rstrip("/") + "/"

    tools = asyncio.run(fetch_tools(url))
    text = SKILL_FILE.read_text(encoding="utf-8").replace("\r\n", "\n")
    if BEGIN not in text or END not in text:
        print(f"{SKILL_FILE}: generated-block markers not found", file=sys.stderr)
        return 2

    before, rest = text.split(BEGIN, 1)
    _, after = rest.split(END, 1)
    updated = before + render(tools) + after

    if args.check:
        if updated != text:
            print(f"{SKILL_FILE} is out of date with {url}; run generate_skill.py", file=sys.stderr)
            return 1
        print("SKILL.md is up to date")
        return 0

    SKILL_FILE.write_text(updated, encoding="utf-8", newline="\n")
    print(f"Wrote {len(tools)} tools from {url} into {SKILL_FILE}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
